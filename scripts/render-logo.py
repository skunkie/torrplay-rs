"""Draws the logo: a 3x3 grid of torrent pieces where the downloaded ones
form a T, for torst, and the last piece of its crossbar, read left to right
as a stream reads, is on its way.

One geometry in two palettes yields every file, so the SVGs and the
bitmaps cannot drift:

- brand/logo-dark.svg and brand/logo-light.svg, a rounded tile on a
  transparent background, for dark and light surroundings;
- brand/logo.svg, the light variant that turns dark where the viewer
  prefers a dark color scheme, for favicons and web pages;
- crates/torrplay-server/assets/dlna/icon-{48,120}.png, the dark tile,
  since televisions cannot say which they prefer and their menus are
  mostly dark;
- crates/torrplay-server/assets/dlna/icon-{48,120}.jpg, the same filled to
  the corners, since JPEG has no transparency.

Run it from the repository root with Pillow 11.3.0:
    python3 scripts/render-logo.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

# The design grid, in units of a 120-unit tile.
TILE = 120
TILE_RADIUS = 26
CELL = 22
GAP = 6
CELL_RADIUS = 5
ORIGIN = (TILE - (3 * CELL + 2 * GAP)) // 2

# The tile, empty pieces, downloaded pieces, and the arriving piece.
DARK = {"tile": "#1E293B", "empty": "#334155", "downloaded": "#38BDF8", "arriving": "#F472B6"}
LIGHT = {"tile": "#F1F5F9", "empty": "#CBD5E1", "downloaded": "#0284C7", "arriving": "#DB2777"}

# (row, column) of each piece that is not empty.
DOWNLOADED_CELLS = {(0, 0), (0, 1), (1, 1), (2, 1)}
ARRIVING_CELL = (0, 2)

# Bitmaps are drawn this many times larger, then reduced, for smooth edges.
SUPERSAMPLE = 8

ICONS = Path("crates/torrplay-server/assets/dlna")
BRAND = Path("brand")

HEADER = """<!--
SPDX-FileCopyrightText: 2026 TorrPlay

SPDX-License-Identifier: MIT

Generated by scripts/render-logo.py; edit the script, not this file.
-->
"""


def cells():
    """Yields each piece's box in tile units and its role in a palette."""
    for row in range(3):
        for column in range(3):
            x = ORIGIN + column * (CELL + GAP)
            y = ORIGIN + row * (CELL + GAP)
            if (row, column) == ARRIVING_CELL:
                role = "arriving"
            elif (row, column) in DOWNLOADED_CELLS:
                role = "downloaded"
            else:
                role = "empty"
            yield x, y, role


def svg(paint, style=""):
    """The tile, with `paint(role)` giving each shape's attributes."""
    pieces = "\n".join(
        f'  <rect x="{x}" y="{y}" width="{CELL}" height="{CELL}" '
        f'rx="{CELL_RADIUS}" {paint(role)}/>'
        for x, y, role in cells()
    )
    return f"""{HEADER}<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}" role="img" aria-label="torst">
{style}  <rect width="{TILE}" height="{TILE}" rx="{TILE_RADIUS}" {paint("tile")}/>
{pieces}
</svg>
"""


def fixed(palette):
    return svg(lambda role: f'fill="{palette[role]}"')


def adaptive():
    def rules(palette):
        return "".join(f" .{role} {{ fill: {color}; }}" for role, color in palette.items())

    style = (
        f"  <style>{rules(LIGHT)}\n"
        f"    @media (prefers-color-scheme: dark) {{{rules(DARK)} }}</style>\n"
    )
    return svg(lambda role: f'class="{role}"', style)


def bitmap(size, rounded, palette=DARK):
    scale = size * SUPERSAMPLE / TILE
    canvas = size * SUPERSAMPLE
    mode, clear = ("RGBA", (0, 0, 0, 0)) if rounded else ("RGB", palette["tile"])
    image = Image.new(mode, (canvas, canvas), clear)
    draw = ImageDraw.Draw(image)
    if rounded:
        draw.rounded_rectangle(
            (0, 0, canvas - 1, canvas - 1),
            radius=TILE_RADIUS * scale,
            fill=palette["tile"],
        )
    for x, y, role in cells():
        draw.rounded_rectangle(
            (x * scale, y * scale, (x + CELL) * scale - 1, (y + CELL) * scale - 1),
            radius=CELL_RADIUS * scale,
            fill=palette[role],
        )
    return image.resize((size, size), Image.Resampling.LANCZOS)


def main():
    BRAND.mkdir(parents=True, exist_ok=True)
    (BRAND / "logo-dark.svg").write_text(fixed(DARK), encoding="utf-8")
    (BRAND / "logo-light.svg").write_text(fixed(LIGHT), encoding="utf-8")
    (BRAND / "logo.svg").write_text(adaptive(), encoding="utf-8")
    ICONS.mkdir(parents=True, exist_ok=True)
    for size in (48, 120):
        bitmap(size, rounded=True).save(ICONS / f"icon-{size}.png", optimize=True)
        bitmap(size, rounded=False).save(
            ICONS / f"icon-{size}.jpg", quality=95, optimize=True
        )


if __name__ == "__main__":
    main()
